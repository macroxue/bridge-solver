// Solve and Shuffle share one busy/idle state: entering hands and running
// either one are mutually exclusive, so this covers both directions.
let busy = false;
// A link opened while a solve or shuffle is running would get that deal's
// results, so it's applied once they're in; see share-url.js.
let deferredUrlHash = null;
const LINK_WAITING_NOTE = ' The new link opens when this finishes.';

// Solve needs the solver loaded, and isn't offered while busy or playing.
function updateSolveBtn() {
  solveBtn.disabled = busy || !!playState || !workerReady;
}

// Shuffle needs every shuffle worker loaded, since a batch can use any.
function updateShuffleBtns() {
  const disabled = busy || shuffleWorkersReadyCount < shuffleWorkers.length;
  shuffle10Btn.disabled = disabled;
  shuffle100Btn.disabled = disabled;
}

function setBusyState(isBusy) {
  busy = isBusy;
  updateSolveBtn();
  updateShuffleBtns();
  setEntryDisabled(busy);
  if (!busy && deferredUrlHash !== null) {
    const hash = deferredUrlHash;
    deferredUrlHash = null;
    loadFromUrl(hash);
  }
}

// Every worker loads its own wasm module independently; only report ready
// once all of them have, since a shuffle batch can land on any pool member.
let workerReady = false;
let shuffleWorkersReadyCount = 0;
function maybeReportReady() {
  const shuffleReady = shuffleWorkersReadyCount === shuffleWorkers.length;
  // Only replaces the loading message, not one about a link loaded meanwhile.
  if (workerReady && shuffleReady && statusEl.textContent === 'Loading solver…') {
    statusEl.textContent = 'Ready.';
  }
}

// Messages from the solver worker (see startup.js).
function onSolverMessage(event) {
  const [type, ...rest] = event.data;
  switch (type) {
    case 'ready':
      workerReady = true;
      updateSolveBtn();
      maybeReportReady();
      if (playsOnReady && playState) requestPlays();
      break;
    case 'abort':
      // The worker is dead: no more Solve or play, and a link waiting on this
      // solve would hide the crash, so drop it.
      workerReady = false;
      deferredUrlHash = null;
      statusEl.textContent = 'Solver crashed: ' + rest[0];
      setBusyState(false);
      break;
    case 'error': {
      const [errType, message] = rest;
      statusEl.textContent = 'Solver error: ' + message;
      if (errType === 'solve' || errType === 'solve_plays') setBusyState(false);
      break;
    }
    case 'solve': {
      const [result, elapsedMs] = rest;
      showDdTable(result);
      statusEl.textContent = `Solved in ${elapsedMs.toFixed(0)} ms.`;
      setBusyState(false);
      break;
    }
    case 'solve_plays': {
      const [result, , requestId] = rest;
      onSolvePlays(result, requestId);
      break;
    }
  }
}

// Splits a hand's suit token (e.g. "KJ1042" or "X") into individual rank
// characters, treating "10" as a single "T" rank.
function parseRanks(token) {
  const ranks = [];
  for (let i = 0; i < token.length; ++i) {
    if (token[i] === '1' && token[i + 1] === '0') {
      ranks.push('T');
      ++i;
    } else {
      ranks.push(token[i].toUpperCase());
    }
  }
  return ranks;
}

// Join/split each seat's four per-suit boxes ("<seat>-S" etc.) and the
// single "SSSS HHHH DDDD CCCC" string the rest of the app uses.
function getHandValue(seat) {
  return SUIT_LETTERS.map(suit => document.getElementById(seat + '-' + suit).value.trim() || '-').join(' ');
}

function setHandValue(seat, value) {
  const suits = value.trim().length ? value.trim().split(/\s+/) : [];
  SUIT_LETTERS.forEach((suit, i) => {
    const token = suits[i];
    document.getElementById(seat + '-' + suit).value = !token || token === '-' ? '' : token;
  });
}

function setHandsDisabled(disabled) {
  for (const seat of SEATS) {
    for (const suit of SUIT_LETTERS) document.getElementById(seat + '-' + suit).disabled = disabled;
  }
  document.getElementById('pasteBox').disabled = disabled;
}

// Locks out anything that could change the deal while a solve is pending,
// so the DD table that eventually comes back always matches the hands
// shown -- otherwise a slow solve plus a mid-solve deal change lets the
// table and the hands (and any contract picked from it) mismatch.
function setEntryDisabled(disabled) {
  dealBtn.disabled = disabled;
  sampleDealEl.disabled = disabled;
  setHandsDisabled(disabled);
}

// Basic client-side validation so obviously bad input (typos, duplicate
// cards, uneven hands) is caught before it reaches solve(). Hands may be
// shorter than 13 cards (endings), but must all be the same length: the
// wasm side aborts on bad characters or a duplicate card, but silently
// accepts uneven hands -- Hands::num_tricks() just reads West's card count,
// with no cross-check against the other three seats -- so it would solve
// something other than the deal you typed.
function validateHands(hands) {
  const seen = new Set();
  const counts = [];
  for (const seat of SEATS) {
    const Seat = seat[0].toUpperCase() + seat.slice(1);
    const value = hands[seat];
    if (!VALID_CHARS.test(value)) {
      return `${Seat}: only card ranks (2-9,T,J,Q,K,A,X), '-' and spaces are allowed.`;
    }
    const suits = value.trim().length ? value.trim().split(/\s+/) : [];
    let cardCount = 0;
    for (let i = 0; i < suits.length && i < 4; ++i) {
      const token = suits[i];
      if (token === '-') continue;
      for (const rank of parseRanks(token)) {
        if (!VALID_RANKS.has(rank)) return `${Seat}: invalid rank '${rank}'.`;
        ++cardCount;
        if (rank === 'X') continue;
        const card = SUIT_LETTERS[i] + rank;
        if (seen.has(card)) return `Duplicate card: ${card}`;
        seen.add(card);
      }
    }
    if (cardCount === 0 || cardCount > 13) {
      return `${Seat}: has ${cardCount} card${cardCount === 1 ? '' : 's'}, expected 1 to 13.`;
    }
    counts.push(cardCount);
  }
  if (counts.some(n => n !== counts[0])) {
    return 'Hands differ in length: ' +
      SEATS.map((seat, i) => `${seat[0].toUpperCase()}${seat.slice(1)} ${counts[i]}`).join(', ') + '.';
  }
  return null;
}

// Cards per hand of an already-validated deal.
function handLength(hands) {
  return parseHandCards(hands.west).length;
}

function showDdTable(result) {
  exitPlay();
  renderTable(result);
  ddFolded = false;
  tableEl.style.display = '';
  growTablesColumnMinWidth();
  updateTableHintText();
  tableHintEl.style.display = 'block';
}

// DECLARER_COLUMNS (declarer-columns.js) maps each DD-table column to its
// declarer; matches solve()'s fixed column order in solver.cc (derived from
// its lead_seats iteration), independent of trump.
// For an ending, columns are the player on lead instead, with the tricks for
// the side on lead: declarer is the leader's right-hand opponent.
function renderTable(result) {
  const lines = result.split('\n').filter(Boolean);
  const n = ddHandLength();
  const ending = n < 13;
  let html = `<table><tr><th>${ending ? 'Lead' : ''}</th>` +
    '<th>South</th><th>North</th><th>West</th><th>East</th></tr>';
  for (const line of lines) {
    const parts = line.trim().split(/\s+/);
    const strain = parts[0];
    const tricks = parts.slice(1, 5).map(Number);
    html += '<tr><td>' + (STRAIN_LABELS[strain] || strain) + '</td>' +
      DECLARER_COLUMNS.map((seat, i) => {
        const declarer = ending ? prevSeat(seat) : seat;
        const t = tricks[DECLARER_COLUMNS.indexOf(declarer)];
        return `<td class="pick" data-strain="${strain}" data-declarer="${declarer}" ` +
          `data-tricks="${t}">${ending ? n - t : t}</td>`;
      }).join('') +
      '</tr>';
  }
  html += '</table>';
  tableEl.innerHTML = html;
  ddLines = lines;
  renderPar();
}

