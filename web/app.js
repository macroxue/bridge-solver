function parText([nsFirst, ewFirst]) {
  const strainLabel = s => STRAIN_LABELS[s];
  const describe = list =>
    `${formatParScore(list)}, ${list.map(c => formatParContract(c, strainLabel)).join(', ')}`;
  if (!nsFirst.length && !ewFirst.length) return '0';
  if (!nsFirst.length || !ewFirst.length) return describe(nsFirst.length ? nsFirst : ewFirst);
  return `${describe(nsFirst)} if N/S bid first; ${describe(ewFirst)} if E/W bid first`;
}

