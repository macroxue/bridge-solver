// Shuffles a fresh 52-card deck and deals 13 cards to each seat, formatted
// as "SSSS HHHH DDDD CCCC" (ranks high to low, '-' for a void suit).
function randomDeal() {
  const deck = [];
  for (let suit = 0; suit < 4; ++suit)
    for (const rank of RANKS) deck.push([suit, rank]);

  for (let i = deck.length - 1; i > 0; --i) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }

  const hands = {};
  SEATS.forEach((seat, s) => {
    const bySuit = [[], [], [], []];
    for (const [suit, rank] of deck.slice(s * 13, s * 13 + 13)) bySuit[suit].push(rank);
    hands[seat] = bySuit
      .map(ranks => ranks.sort((a, b) => RANKS.indexOf(a) - RANKS.indexOf(b)))
      .map(ranks => ranks.length ? ranks.join('') : '-')
      .join(' ');
  });
  return hands;
}

